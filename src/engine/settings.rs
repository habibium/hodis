//! Generation of the embedded instance's `settings.yml`.

use std::fmt::Write as _;
use std::net::TcpListener;

use anyhow::{Context, Result};

/// Hex-encoded 256-bit key for `server.secret_key`; being hex it never needs
/// YAML escaping.
pub fn secret_key() -> Result<String> {
    let mut bytes = [0_u8; 32];
    getrandom::fill(&mut bytes).context("no operating system entropy for the instance secret")?;

    let mut key = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        write!(key, "{byte:02x}").expect("writing to a String cannot fail");
    }
    Ok(key)
}

/// The port is recorded and reused for the life of the install, so the gap
/// between this probe and the instance binding is a first-run concern only.
pub fn free_port() -> Result<u16> {
    let listener =
        TcpListener::bind(("127.0.0.1", 0)).context("no free port on the loopback interface")?;
    let port = listener
        .local_addr()
        .context("bound listener has no address")?
        .port();
    Ok(port)
}

/// Holding the port steady across re-provisions makes a leftover instance
/// collide visibly instead of being orphaned on a port nothing reads.
pub fn choose_port(preferred: Option<u16>) -> Result<u16> {
    if let Some(port) = preferred
        && TcpListener::bind(("127.0.0.1", port)).is_ok()
    {
        return Ok(port);
    }
    free_port()
}

/// Only the deltas from upstream's defaults. A list given under
/// `use_default_settings` replaces rather than extends the default, so
/// `formats` is exactly these two — and without `json` SearXNG answers 403.
#[must_use]
pub fn render(secret_key: &str, port: u16) -> String {
    format!(
        "# Generated by hodis for its embedded SearXNG instance.
# Rewritten whenever the instance is provisioned; edits are not preserved.
use_default_settings: true

general:
  instance_name: \"hodis\"
  debug: false

server:
  bind_address: \"127.0.0.1\"
  port: {port}
  secret_key: \"{secret_key}\"
  # The limiter defends public instances; this one is single-user loopback.
  limiter: false
  public_instance: false

search:
  formats:
    - html
    - json
"
    )
}

#[cfg(test)]
mod tests {
    use std::net::TcpListener;

    use super::{choose_port, free_port, render, secret_key};

    #[test]
    fn settings_enable_the_json_format_hodis_queries() {
        // Without `json` in formats, SearXNG answers a search with 403.
        let settings = render("abc123", 8899);
        assert!(
            settings.contains("formats:\n    - html\n    - json\n"),
            "json must be an enabled format:\n{settings}"
        );
    }

    #[test]
    fn settings_keep_the_instance_private_and_local() {
        let settings = render("abc123", 8899);
        for expected in [
            "use_default_settings: true",
            "bind_address: \"127.0.0.1\"",
            "port: 8899",
            "secret_key: \"abc123\"",
            "limiter: false",
            "public_instance: false",
        ] {
            assert!(
                settings.contains(expected),
                "settings must contain {expected:?}:\n{settings}"
            );
        }
    }

    #[test]
    fn a_generated_secret_is_256_bits_of_hex() {
        let key = secret_key().expect("the system provides entropy");
        assert_eq!(key.len(), 64, "32 bytes render as 64 hex digits");
        assert!(
            key.chars().all(|c| c.is_ascii_hexdigit()),
            "a hex key needs no yaml escaping: {key}"
        );
    }

    #[test]
    fn generated_secrets_differ() {
        let (first, second) = (
            secret_key().expect("the system provides entropy"),
            secret_key().expect("the system provides entropy"),
        );
        assert_ne!(first, second, "each instance gets its own secret");
    }

    #[test]
    fn a_chosen_port_is_free_to_bind() {
        let port = free_port().expect("the loopback interface has a free port");
        assert_ne!(port, 0, "the ephemeral port must be resolved to a real one");
        TcpListener::bind(("127.0.0.1", port))
            .expect("the port free_port reported must be bindable afterwards");
    }

    #[test]
    fn a_still_free_port_is_kept_across_provisions() {
        let previous = free_port().expect("the loopback interface has a free port");
        assert_eq!(
            choose_port(Some(previous)).expect("an unused port stays chosen"),
            previous,
            "re-provisioning must not move an instance that can stay put"
        );
    }

    #[test]
    fn a_taken_port_is_replaced() {
        // Hold the port open so choose_port cannot bind it.
        let occupied = TcpListener::bind(("127.0.0.1", 0)).expect("a port is available");
        let taken = occupied
            .local_addr()
            .expect("bound listener has an address")
            .port();

        let chosen = choose_port(Some(taken)).expect("a fresh port is available");
        assert_ne!(chosen, taken, "a port in use must not be handed out again");
    }

    #[test]
    fn no_preference_still_yields_a_port() {
        let port = choose_port(None).expect("the loopback interface has a free port");
        assert_ne!(port, 0);
    }
}
